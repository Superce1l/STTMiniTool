# ── 2.2.3 更新汇总（本地改进版，基于上游 2.0.0）────────────────────────────
#   本版聚焦「断句质量」——修复字幕一行内混有「上一句下半段＋下一句上半段」
#   的问题（OCR 代码审查确认修复方向，2 项审查意见均已采纳）。
#   断句：共享分行器新增「声学停顿切行」——模型漏打标点时，以字级时间轴的
#         字间空隙（≥0.35s）作为补充句界，等同看不见的逗号，两句不再黏连；
#         MAX_CHARS 兜底换行改为回退到行内最长的可信停顿处切开，切点尽量
#         贴近语义边界，不再机械地按字数硬切。
#   切片：长语音段（超模型上限）的音频切分由「固定秒数硬切」改为
#         「等分＋切点吸附到能量最低的停顿处」（±1.5s 搜索窗）——不再把
#         字词劈成两半；等分片数 + 可行窗约束（每片 ≤ 上限且不产生丢弃
#         碎片），修掉了「末段可能超长被 mel 静默截断掉字」的隐患
#         （OCR 审查指出，原建议的一次性钳位经验证会把超限转移到中间片，
#         改为数学上可证的可行窗方案）。
#   合并：长音频切片的重叠区去重改为「保留更完整的版本」（文字更长者优先）
#         ——跨片首的句子完整版在前片、跨界尾的完整版在后片，无条件取任一
#         侧都会丢字（OCR 审查指出后修正）；同时保留后片时间戳靠近片缘的
#         优势，避免重叠区出现残句或重复行。

